"""
LegalMitra State & Union Territory Legislation Registry
Comprehensive registry of all 28 States and 8 Union Territories in India,
including their jurisdiction codes, official legislative portals, gazette authorities,
and current ingestion status.
"""

from typing import Dict, List, Optional
from pydantic import BaseModel, Field


class StateUTRecord(BaseModel):
    jurisdiction_code: str = Field(..., description="e.g. 'IN-DL', 'IN-MH', 'IN-KA'")
    name: str = Field(..., description="Official name of the State or Union Territory")
    category: str = Field(..., description="'State' or 'Union Territory'")
    official_portal_name: str = Field(..., description="Name of state code or legislative portal")
    official_portal_url: str = Field(..., description="URL of official portal or India Code state portal")
    gazette_portal_url: Optional[str] = Field(default=None, description="Official state gazette portal")
    responsible_authority: str = Field(..., description="e.g. 'Department of Law and Justice, Government of NCT of Delhi'")
    active_in_pilot: bool = Field(default=False)
    ingested_acts_count: int = Field(default=0)
    priority_level: str = Field(default="Phase 16 Core", description="Priority tier for corpus expansion")
    notes: Optional[str] = Field(default=None)


