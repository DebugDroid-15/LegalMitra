def export_state_registry_json(output_path: str = "data/08_corpus/state_ut_registry.json") -> None:
    import json
    data = [rec.model_dump() for rec in STATE_UT_REGISTRY]
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)
    print(f"Exported {len(STATE_UT_REGISTRY)} State and UT records to {output_path}")


if __name__ == "__main__":
    export_state_registry_json()
