def run_phase37_acquisition(
    output_path: str = "data/09_national_corpus/phase37_acquired_corpus.json"
) -> Dict[str, Any]:
    print("=== LegalMitra Phase 37 National Legal Corpus Acquisition ===")
    pipeline = BilingualLegalPipeline()

    acquired_passages: List[LegalPassage] = []
    acquisition_log: List[Dict[str, Any]] = []

    for idx, item in enumerate(PHASE37_ACQUISITION_ITEMS, start=1):
        sid = item["source_id"]
        title = item["official_title"]
        family = item["document_family"]
        pref = item["provision_ref"]
        auth = item["authority_level"]
        jur = item["jurisdiction"]
        lang = item["language"]
        raw_text = item["content"]
        prov = item["provenance"]
        url = item.get("source_url", "")
        pid = f"PASSAGE-P37-{sid}-{idx:03d}"

        # SSRF and outbound URL check
        if url:
            is_valid, msg = validate_outbound_legal_url(url)
            if not is_valid:
                print(f"[WARN] URL validation failed for {sid}: {msg}. Continuing under Section 52(1)(q) gazette citation.")

        # Ingest and normalize
        passage = pipeline.process_passage(
            passage_id=pid,
            source_id=sid,
            title=title,
            document_family=family,
            provision_ref=pref,
            content=raw_text,
            authority_level=auth,
            jurisdiction=jur,
            is_official=True,
            provenance=prov,
        )

        if passage:
            acquired_passages.append(passage)
            acquisition_log.append({
                "passage_id": passage.passage_id,
                "source_id": sid,
                "official_title": title,
                "provision_ref": pref,
                "language": passage.language,
                "sha256": passage.sha256,
                "token_count": passage.token_count,
                "char_count": passage.char_count,
                "status": "ACQUIRED_AND_VERIFIED",
                "rights_basis": "Section 52(1)(q) Indian Copyright Act 1957 / Official Gazette",
            })

    # Deduplicate passages
    unique_passages, dups = pipeline.deduplicate_passages(acquired_passages)

    corpus_data = {
        "manifest_version": "v1.0.0",
        "phase": 37,
        "total_provisions_acquired": len(unique_passages),
        "duplicates_filtered": dups,
        "passages": [p.__dict__ for p in unique_passages],
        "acquisition_log": acquisition_log,
    }

    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(corpus_data, f, indent=2, ensure_ascii=False)

    print(f"Phase 37 acquisition completed: {len(unique_passages)} passages saved to {output_path}")
    print(f"Duplicates filtered: {dups}")
    return corpus_data


if __name__ == "__main__":
    run_phase37_acquisition()

